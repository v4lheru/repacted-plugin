"""_docsgen: render the reference pages and the troubleshooting page from the plugin tree.

Location: pact-plugin/bin/_docsgen.py. Used by bin/repact-docs-gen (the CLI) and
tests/test_docsgen.py (through the CLI). Reads the tree through _docsgen_source.ShippedTree,
so only what ships is listed and its text is the shipped text.

Each page is Markdown with hand-written prose around generated regions,
`<!-- generated:<name> -->` ... `<!-- /generated -->` (hooks/shared/marked_regions.py). A
run replaces the region bodies and keeps the prose; a page that does not exist yet starts
from the skeleton below. `check_pages` renders the same text and reports every page that
differs from disk, which is what CI runs.

Pages (paths relative to the target root):
    docs/reference/{commands,agents,skills,bin,config,rules,compat}.md
    docs/troubleshooting.md      one explicit anchor per rule id in hooks/shared/rules.py

Example:
    results = run(Path(plugin_root), Path(target_root), PAGES, check=True)
"""

