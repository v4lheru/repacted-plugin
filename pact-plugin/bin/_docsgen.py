_INTERNAL_TAG = re.compile(r"\s*\((?:Wave [^)]*|D\d+[a-z]?(?: [A-Z]+)*)\)")
_SKILL_TAG = re.compile(r"\s*\(repacted:([a-z0-9-]+)\)")
_SENTENCE_END = re.compile(r"(?<=[.!?])\s+(?=[A-Z`])")


# --- collectors -------------------------------------------------------------------------

def _markdown_units(tree: ShippedTree, directory: str) -> List[Tuple[str, dict]]:
    units = []
    for name in tree.listdir(directory):
        rel = f"{directory}/{name}"
        if name.endswith(".md"):
            text = tree.text(rel)
            if text is not None:
                units.append((name[:-3], frontmatter(text)))
    return units


def collect_skills(tree: ShippedTree) -> List[Tuple[str, str]]:
    rows = []
    for name in tree.listdir("skills"):
        text = tree.text(f"skills/{name}/SKILL.md")
        if text is not None:
            fields = frontmatter(text)
            rows.append((fields.get("name") or name, fields.get("description", "")))
    return sorted(rows, key=lambda row: row[0].lower())


def collect_bin(tree: ShippedTree, skill_names: set) -> List[Tuple[str, str]]:
    rows = []
    for name in tree.listdir("bin"):
        rel = f"bin/{name}"
        if name.startswith(("_", ".")) or "." in name or not tree.is_executable(rel):
            continue
        text = tree.text(rel)
        if text is not None:
            rows.append((name, _tool_summary(name, script_summary(text), skill_names)))
    return rows


def _tool_summary(name: str, paragraph: str, skill_names: set) -> str:
    text = re.sub(rf"^{re.escape(name)}(?:\s*\([^)]*\))?\s*(?::|—|-)\s*", "", paragraph)
    text = _SENTENCE_END.split(text, 1)[0]
    text = _INTERNAL_TAG.sub("", text)
    text = _SKILL_TAG.sub(lambda m: m.group(0) if m.group(1) in skill_names else "", text)
    return text


def rule_family(rule_id: str) -> str:
    if rule_id.endswith(".timeout"):
        return "timeout"
    if rule_id.endswith(".error"):
        return "error"
    if rule_id.startswith("mg.inert."):
        return "inert"
    for prefix, family in (("env.", "env"), ("process.", "process"), ("mg.", "mg"),
                           ("dispatch.", "session"), ("dispatch_gate.project_", "agents"),
                           ("dispatch_gate.session_cost", "budget")):
        if rule_id.startswith(prefix):
            return family
    if rule_id == "team_config_absent":
        return "session"
    raise SourceError(f"rule id {rule_id!r} has no family; add one to FAMILIES in bin/_docsgen.py")


# --- renderers --------------------------------------------------------------------------

def _prose(text: str) -> str:
    """One line of Markdown: whitespace folded, `<` and `>` outside code spans escaped (an
    unescaped `<task>` reads as an HTML tag), a leading bare identifier put in a code span."""
    parts = " ".join(str(text).split()).split("`")
    for i in range(0, len(parts), 2):
        parts[i] = parts[i].replace("<", "&lt;").replace(">", "&gt;")
    line = "`".join(parts)
    first, _, rest = line.partition(" ")
    if "_" in first and not first.startswith("`"):
        return f"`{first}` {rest}"
    return line[:1].upper() + line[1:]


def _cell(text: str) -> str:
    return _prose(text).replace("|", "\\|")


def _table(header: Tuple[str, ...], rows: List[Tuple[str, ...]]) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(_cell(c) for c in row) + " |" for row in rows]
    return "\n".join(lines)


def render_commands(tree: ShippedTree) -> Dict[str, str]:
    rows = [(f"`/{PREFIX}:{stem}`", fields.get("description", ""),
             f"`{fields['argument-hint']}`" if fields.get("argument-hint") else "")
            for stem, fields in sorted(_markdown_units(tree, "commands"),
                                       key=lambda unit: unit[0].lower())]
    return {"commands": _table(("Command", "What it does", "Arguments"), rows)}


def render_agents(tree: ShippedTree) -> Dict[str, str]:
    rows = sorted(((f"`{fields.get('name') or stem}`", fields.get("description", ""))
                   for stem, fields in _markdown_units(tree, "agents")),
                  key=lambda row: row[0].lower())
    return {"agents": _table(("Agent", "What it does"), rows)}


def render_skills(tree: ShippedTree) -> Dict[str, str]:
    rows = [(f"`{PREFIX}:{name}`", description) for name, description in collect_skills(tree)]
    return {"skills": _table(("Skill", "Use it when"), rows)}


def render_bin(tree: ShippedTree) -> Dict[str, str]:
    skills = {name for name, _ in collect_skills(tree)}
    rows = [(f"`{name}`", summary) for name, summary in collect_bin(tree, skills)]
    return {"bin": _table(("Tool", "What it does"), rows)}


def render_config(tree: ShippedTree) -> Dict[str, str]:
    config = tree.load_module("hooks/shared/pact_config.py", "_docsgen_pact_config")
    readers = {"llm": "the lead, at session start", "hook": "a hook"}
    options = []
    for name, row in config._REGISTRY.items():
        if row["type"] == "bool":
            default = "`1` (on)" if row["default"] else "`0` (off)"
            values = "`1`, `true`, `yes` or `on` turn it on; anything else is off"
        elif row["type"] == "usd":
            default = "unset (no cap)"
            values = (f"a plain number of US dollars above 0, at most {config.USD_MAX:,}; "
                      "anything else is ignored and noted")
        else:
            default = f"`{row['default']}`"
            values = ", ".join(f"`{v}`" for v in row["allowed"])
        options.append((f"`{name}`", row["type"], default, values,
                        readers.get(row["consumer"], row["consumer"])))
    profile_text = tree.text("templates/profile.example.json")
    if profile_text is None:
        raise SourceError("templates/profile.example.json does not ship")
    profile = [(f"`{key}`", f"`{json.dumps(value)}`")
               for key, value in _flatten(json.loads(profile_text))]
    return {"options": _table(("Option", "Type", "Default", "Values", "Read by"), options),
            "profile": _table(("Key", "Example value"), profile)}


def _flatten(data: dict, prefix: str = "") -> List[Tuple[str, object]]:
    pairs = []
    for key, value in data.items():
        if key.startswith("_"):
            continue
        path = f"{prefix}{key}"
        if isinstance(value, dict) and value:
            pairs += _flatten(value, f"{path}.")
        else:
            pairs.append((path, value))
    return pairs


def _load_rules(tree: ShippedTree):
    return tree.load_module("hooks/shared/rules.py", "_docsgen_rules")


def render_rules(tree: ShippedTree) -> Dict[str, str]:
    rules = _load_rules(tree)
    rows = [(f"`{rule_id}`", rule.explain,
             f"[way through](../troubleshooting.md#{rules.anchor(rule_id)})")
            for rule_id, rule in rules.RULES.items()]
    return {"rules": _table(("Rule id", "What it means", "Fix"), rows)}


def render_troubleshooting(tree: ShippedTree) -> Dict[str, str]:
    rules = _load_rules(tree)
    by_family: Dict[str, list] = {key: [] for key, _, _ in FAMILIES}
    for rule_id, rule in rules.RULES.items():
        by_family[rule_family(rule_id)].append((rule_id, rule))
    blocks = []
    for key, heading, why in FAMILIES:
        if not by_family[key]:
            continue
        blocks.append(f"## {heading}")
        for rule_id, rule in by_family[key]:
            blocks.append(f'<a id="{rules.anchor(rule_id)}"></a>\n### `{rule_id}`\n\n'
                          f"- **Rule:** {_prose(rule.explain)}\n"
                          f"- **Why:** {_prose(getattr(rule, 'why', '') or why)}\n"
                          f"- **Way through:** {_prose(rule.instead)}")
    return {"troubleshooting": "\n\n".join(blocks)}


def render_compat(tree: ShippedTree) -> Dict[str, str]:
    text = tree.text("reference/compat.json")
    if text is None:
        raise SourceError("reference/compat.json does not ship")
    data = json.loads(text)
    host, os_info = data.get("claude_code", {}), data.get("os", {})
    codes = lambda values: ", ".join(f"`{v}`" for v in values) or "none"   # noqa: E731
    rows = [("Claude Code, tested", codes(host.get("tested", []))),
            ("Python, minimum", codes([data.get("python", {}).get("min", "")])),
            ("Operating systems, tested", codes(os_info.get("tested", []))),
            ("Operating systems, expected to work", codes(os_info.get("expected", []))),
            ("As of", codes([data.get("as_of", "")]))]
    return {"compat": _table(("Host", "Versions"), rows)}


RENDERERS = {
    "commands": render_commands, "agents": render_agents, "skills": render_skills,
    "bin": render_bin, "config": render_config, "rules": render_rules,
    "compat": render_compat, "troubleshooting": render_troubleshooting,
}




# --- pages ------------------------------------------------------------------------------

def skeleton(key: str) -> str:
    _, title, intro, regions = PAGES[key]
    parts = [f"# {title}", intro, MARKER_NOTE]
    parts += [f"<!-- {KIND}:{name} -->\n<!-- /{KIND} -->" for name in regions]
    return "\n\n".join(parts) + "\n"


def render_page(tree: ShippedTree, key: str, current: str, regions_mod) -> str:
    bodies = RENDERERS[key](tree)
    text = current
    for name in PAGES[key][3]:
        text = regions_mod.replace_region(text, name, f"\n{bodies[name]}\n", kind=KIND)
    return text


def run(plugin_root: Path, target_root: Path, keys: List[str],
        check: bool) -> Tuple[List[Tuple[str, str]], str]:
    """Render each page; write it (or, with check, only compare).

    Returns ([(status, page path)], mode); status is wrote, unchanged, differs or missing.
    Raises SourceError when the tree cannot be read or a page lost its markers.
    """
    tree = ShippedTree(plugin_root)
    regions_mod = tree.load_module("hooks/shared/marked_regions.py", "_docsgen_regions")
    results = []
    for key in keys:
        path = target_root / PAGES[key][0]
        on_disk = path.read_text(encoding="utf-8") if path.is_file() else None
        try:
            fresh = render_page(tree, key, on_disk if on_disk is not None else skeleton(key),
                                regions_mod)
        except regions_mod.RegionError as error:
            raise SourceError(f"{path}: {error}") from error
        if fresh == on_disk:
            results.append(("unchanged", PAGES[key][0]))
        elif check:
            results.append(("differs" if on_disk is not None else "missing", PAGES[key][0]))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(fresh, encoding="utf-8")
            results.append(("wrote", PAGES[key][0]))
    return results, tree.mode
