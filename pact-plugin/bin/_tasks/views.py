def _clock(state) -> Optional[datetime.datetime]:
    """The log's newest event time: the render's only notion of now."""
    stamps = [task["updated"] for task in state.tasks.values()]
    if not stamps:
        return None
    return datetime.datetime.strptime(max(stamps), "%Y-%m-%dT%H:%M:%S.%fZ").replace(
        tzinfo=datetime.timezone.utc)


def _credential(text: str) -> Optional[str]:
    return common.credential_reason(W.TEXT_PATH, text) if text else None


def _withhold_lines(lines: Iterable[str]) -> List[str]:
    """The D25 net under every view line (text, links, evidence alike): a line that carries a
    credential is replaced whole, keeping only the task refs on it so the lead can find them."""
    out = []
    for line in lines:
        kind = _credential(line)
        if kind:
            refs = " ".join(f"`{ref}`" for ref in dict.fromkeys(PT_REF_IN_TEXT.findall(line)))
            line = f"(withheld: this line carried a credential value ({kind})) {refs}".rstrip()
        out.append(line)
    return out


def _text(value) -> str:
    """One line of task text, with the USER-OWNED marker reserved for the owner field."""
    return PT.one_line(value or "", 500).replace("**", "*").replace(USER_OWNED, "user-owned")


def _cell(value) -> str:
    return _text(value).replace("|", "\\|")


def _title(task: dict) -> str:
    return _text(task["title"])


def _order(task: dict):
    return PT._order(task)


def _links(task: dict, prefix: str) -> List[str]:
    return [link["target"][len(prefix):] for link in task["links"] if link["target"].startswith(prefix)]


def _ptask_id(task: dict) -> Optional[int]:
    for rest in _links(task, "ptask:"):
        tail = rest.rsplit("/", 1)[-1]
        if tail.isdigit():
            return int(tail)
    return None


def release_name(task: dict) -> Optional[str]:
    if RELEASE_TAG not in task["tags"]:
        return None
    return next((tag[len(RELEASE_PREFIX):] for tag in task["tags"]
                 if tag.startswith(RELEASE_PREFIX) and len(tag) > len(RELEASE_PREFIX)), None)


def releases(state) -> List[Tuple[str, dict, List[dict]]]:
    """(tag, release task, [gate tasks]) in creation order; dropped releases and gates are out."""
    live = sorted((task for task in state.tasks.values()
                   if task["status"] != "dropped" and release_name(task)),
                  key=lambda task: (task["created"], task["ref"]))
    out = []
    for release in live:
        gates = sorted((task for task in state.tasks.values()
                        if task["parent"] == release["ref"] and GATE_TAG in task["tags"]
                        and task["status"] != "dropped"),
                       key=lambda task: (task["created"], task["ref"]))
        out.append((release_name(release), release, gates))
    return out


def gate_entry(task: dict) -> dict:
    passed = task["status"] == "done"
    verified = [item["target"] for item in task["evidence"] if item["verified"]]
    gate, note = task["title"], task.get("note") or ""
    if gate.endswith("…") and note.startswith(gate[:-1]):
        gate = note                                  # the importer keeps a long gate's full text here
    kind = _credential(gate)
    evidence = "; ".join(verified) if passed else None
    if evidence and _credential(evidence):
        evidence = "(withheld)"
    return {"gate": f"(withheld: {kind})" if kind else gate, "task_id": _ptask_id(task),
            "status": "passed" if passed else "pending", "evidence": evidence}


def _markdown(lines: List[str]) -> str:
    body = "\n".join(_withhold_lines(lines)) + "\n"
    digest = hashlib.sha256(body.encode("utf-8")).hexdigest()
    return body + f"<!-- render-hash: sha256:{digest} -->\n"


def _json_body(doc: dict) -> str:
    return json.dumps(doc, indent=2, ensure_ascii=False)


