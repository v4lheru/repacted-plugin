"""Generated views of the project task log (D10 P4a; design sections 8 and 10).

Location: pact-plugin/bin/_tasks/views.py. Used by bin/repact-task (`render`, `commit`,
and the re-render after every write). Three views of the log and two of the ledger, each a pure
function of what it renders:
  backlog        docs/backlog.md: open tasks by tag, then what settled in the last 14 days; an
                 open owner=user task carries the `(USER-OWNED)` marker D5 check 8 reads.
  progress       docs/progress.md: in flight, blocked (with the reason), release gates, waiting
                 on the user, ready next, recently done, recent notes and decisions, and a static
                 "resuming after a break" block. It alone is enough to resume from (D10 P5).
  release_gates  docs/release-gates.json in D5's ruled shape {gates: {tag: [{gate, task_id,
                 status, evidence}]}}, so check 9 reads it unchanged.
  known_limits   docs/known-limits.md: the newest 50 ledger limits that are not retired (the
                 config key "known_limits_max" changes the number), grouped by project task,
                 newest first, with a count of the rest (hooks/shared/task_log/ledger.py),
                 added to the configured views once .repacted/ledger.jsonl exists.
  decision_log   docs/decision-log.md: the ledger's DL<n> decisions. Opt-in: rendered only when
                 the config's views name it ("decision_log": "docs/decision-log.md").
                 The ledger views escape their model-written text.
Gate model (lead ruling amend_1 on #186, a change to design section 10): a RELEASE task per tag,
tagged `release` and `release.<tag>`, with each gate a child task tagged `gate`. A release with
no gate children renders as []; task_id comes from the gate's `ptask:<team>/<id>` link; a done
gate is `passed` with its verified evidence. An uncut tag has no `tag:` link until it exists.

Which views exist, and where, is `.repacted/config.json` ({"views": {name: repo-relative path}});
without it nothing renders. Every view opens with HEADER and ends with a render hash, so a hand
edit is detectable (hand_edited). The render clock is the log's newest event, never the wall, so
the same log renders the same bytes. Every line passes the D25 check: a line that carries a
credential is withheld whole, never masked.
"""
