def _backlog_line(state, task: dict, children: Optional[Dict[str, List[str]]] = None) -> str:
    marker = f" ({USER_OWNED})" if task["owner"] == "user" and task["status"] not in PT.SETTLED else ""
    owner = f" · {task['owner']}" if task["owner"] and task["owner"] != "user" else ""
    note = f" · {_text(task['note'])}" if task.get("note") else ""
    struck = "~~" if task["status"] in PT.SETTLED else ""
    return (f"- {struck}**{_text(task['title'])}**{struck}{marker}. `{task['ref']}` {task['priority']} "
            f"{PT.classify(state, task['ref'], children)}{owner}{note}")


def render_backlog(state) -> str:
    now = _clock(state)
    open_tasks = sorted((t for t in state.tasks.values() if t["status"] not in PT.SETTLED), key=_order)
    groups: Dict[str, List[dict]] = {}
    children = PT.open_children(state)
    for task in open_tasks:
        groups.setdefault(task["tags"][0] if task["tags"] else "", []).append(task)
    lines = [f"<!-- {HEADER} -->", "# Backlog", "",
             f"Open tasks by tag, then what settled in the {RECENT_DAYS} days before the log's newest event."]
    for tag in sorted(name for name in groups if name) + ([""] if "" in groups else []):
        lines += ["", f"## {tag or 'untagged'}", ""]
        lines += [_backlog_line(state, task, children) for task in groups[tag]]
    recent = sorted((t for t in state.tasks.values() if t["status"] in PT.SETTLED and now is not None
                     and PT._age_days(t["updated"], now) <= RECENT_DAYS),
                    key=lambda t: (t["updated"], t["ref"]), reverse=True)
    lines += ["", f"## Done or dropped in the last {RECENT_DAYS} days", ""]
    lines += [_backlog_line(state, task, children) for task in recent] or ["- none"]
    return _markdown(lines)


def _gate_lines(state) -> List[str]:
    """A count, one line per gate, and ONE line for every release that needs no gate."""
    out, gate_free, total, passed = [], [], 0, 0
    for tag, _release, gates in releases(state):
        if not gates:
            gate_free.append(f"`{tag}`")
        for gate in gates:
            entry = gate_entry(gate)
            total += 1
            passed += entry["status"] == "passed"
            task_id = f", task #{entry['task_id']}" if entry["task_id"] is not None else ""
            out.append(f"- `{tag}`: {_text(entry['gate'])} ({entry['status']}{task_id}) `{gate['ref']}`")
    if gate_free:
        out.append("- no gate: " + ", ".join(gate_free))
    if not out:
        return ["- none"]
    return [f"{passed} of {total} gates passed.", ""] + out


def _blocked_lines(state) -> List[str]:
    """Each task that cannot start, with why: what it waits on, or the note of a manual block."""
    out = []
    for task, kind, who in PT.blocked(state):
        why = f"{kind}: {', '.join(who)}" if who else kind
        if kind == "blocked" and task.get("note"):
            why += f": {_text(task['note'])}"
        out.append(f"- `{task['ref']}` {_title(task)} ({why})")
    return out or ["- none"]


def _newest(tasks: Iterable[dict]) -> List[dict]:
    return sorted(tasks, key=lambda task: (task["updated"], task["ref"]), reverse=True)[:RECENT_SHOWN]


def _recent_done_lines(state) -> List[str]:
    done = _newest(t for t in state.tasks.values() if t["status"] == "done")
    lines = []
    for task in done:
        verified = [item["target"] for item in task["evidence"] if item["verified"]]
        evidence = f" · {', '.join(verified)}" if verified else ""
        lines.append(f"- {task['updated'][:10]} `{task['ref']}` {_title(task)}{evidence}")
    return lines or ["- none"]


def _recent_note_lines(state) -> List[str]:
    """Where open work stands; a settled task's note is history (it is under Recently done)."""
    noted = _newest(t for t in state.tasks.values() if t.get("note") and t["status"] not in PT.SETTLED)
    return [f"- {t['updated'][:10]} `{t['ref']}` {_title(t)}: {_text(t['note'])}" for t in noted] \
        or ["- none"]


def _recent_decision_lines(state) -> List[str]:
    """Decisions reach the log as `decision:D<n>` links (their text is in docs/decisions.md)."""
    decided = _newest(t for t in state.tasks.values() if _links(t, "decision:"))
    return [f"- {', '.join(_links(t, 'decision:'))} `{t['ref']}` {_title(t)}" for t in decided] \
        or ["- none"]


def render_progress(state) -> str:
    lines = [f"<!-- {HEADER} -->", "# Progress", "", "## In flight", "",
             "| Task | Owner | Title | Branch | Platform task |", "|---|---|---|---|---|"]
    for task in PT.active(state):
        lines.append(f"| `{task['ref']}` | {_cell(task['owner'] or '-')} | {_title(task).replace('|', chr(92) + '|')} | "
                     f"{_cell(', '.join(_links(task, 'branch:')) or '-')} | "
                     f"{_cell(', '.join(_links(task, 'ptask:')) or '-')} |")
    lines += ["", "## Blocked", ""] + _blocked_lines(state)
    lines += ["", "## Release gates", ""] + _gate_lines(state)
    lines += ["", "## Waiting on the user", ""]
    waiting = sorted((t for t in state.tasks.values() if t["owner"] == "user" and t["status"] not in PT.SETTLED),
                     key=_order)
    lines += [f"- **{_title(t)}** `{t['ref']}`" for t in waiting] or ["- none"]
    lines += ["", "## Ready next", ""]
    lines += [f"- `{t['ref']}` {t['priority']} {_title(t)}" for t in PT.ready(state)[:READY_SHOWN]] \
        or ["- none"]
    lines += ["", "## Recently done", ""] + _recent_done_lines(state)
    lines += ["", "## Recent notes", ""] + _recent_note_lines(state)
    lines += ["", "## Recent decisions", ""] + _recent_decision_lines(state)
    lines += ["", "## Resuming after a break", "", *RESUME_BLOCK]
    return _markdown(lines)


def render_release_gates(state) -> str:
    gates: Dict[str, List[dict]] = {}
    for tag, _release, children in releases(state):
        gates.setdefault(tag, []).extend(gate_entry(gate) for gate in children)
    doc = {"_generated": HEADER, "_doc": GATES_DOC, "gates": gates}
    digest = hashlib.sha256(_json_body(doc).encode("utf-8")).hexdigest()
    return _json_body({**doc, HASH_KEY: f"sha256:{digest}"}) + "\n"


RENDERERS = {"backlog": render_backlog, "progress": render_progress,
             "release_gates": render_release_gates}


