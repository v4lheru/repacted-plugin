LEDGER_TEXT_MAX = 4096
KNOWN_LIMITS_MAX = 50               # the page lists this many open limits; the rest are counted
LIMITS_MAX_KEY = "known_limits_max"
LIMITS_MAX_CEILING = 10000
MARKDOWN_SPECIAL_RE = re.compile(r"([\\`*_\[\]<>|!~&])")
LIMITS_INTRO = ("What the accepted HANDOFFs said this project does not do yet, or does only in part: "
                "each `known-limit:` line, under the project task it belongs to (or the platform "
                "task that reported it, when none is bound), newest first. A limit leaves this page "
                "when a later accepted HANDOFF of the same task reports it `fixed:` (or names its "
                "id: `fixed: id <id>`), or with "
                "`repact-task ledger retire <id> --reason <text>`.")
DECISIONS_INTRO = ("Implementation decisions from the accepted HANDOFFs, numbered DL<n> in the order "
                   "the lead accepted them. These are the specialists' choices, not the user's "
                   "rulings (those are D<n>).")


def _plain(value) -> str:
    """Model-written ledger text as inert Markdown: one line, the USER-OWNED marker reserved, and
    every character that opens emphasis, code, a link, an image, raw HTML, an entity, a table
    cell or a strikethrough escaped with a backslash, so it renders as the literal text."""
    flat = PT.one_line(LG.flatten(value or ""), LEDGER_TEXT_MAX).replace(USER_OWNED, "user-owned")
    return MARKDOWN_SPECIAL_RE.sub(r"\\\1", flat)


def limits_cap(main: Path) -> int:
    """How many open limits docs/known-limits.md lists: the config's known_limits_max (an integer
    from 1 to LIMITS_MAX_CEILING), else KNOWN_LIMITS_MAX."""
    path = Path(main) / CONFIG_RELPATH
    if not path.exists():
        return KNOWN_LIMITS_MAX
    try:
        value = json.loads(path.read_text(encoding="utf-8")).get(LIMITS_MAX_KEY, KNOWN_LIMITS_MAX)
    except (OSError, ValueError, AttributeError) as err:
        raise W.Refused(f"{CONFIG_RELPATH} is not a JSON object: {err}") from err
    if not isinstance(value, int) or isinstance(value, bool) or not 1 <= value <= LIMITS_MAX_CEILING:
        raise W.Refused(f"{CONFIG_RELPATH}: {LIMITS_MAX_KEY} must be a whole number from 1 to "
                        f"{LIMITS_MAX_CEILING} (the default is {KNOWN_LIMITS_MAX})")
    return value


def _limit_group(state, ptask: str) -> Tuple[str, str]:
    """(group key, heading) for a limit: its first bound project task, else its platform task."""
    refs = LG.project_refs(state, ptask) if state is not None else []
    if not refs:
        return ptask, f"## `{ptask}`"
    task = state.tasks[refs[0]]
    more = f" (and {len(refs) - 1} more)" if len(refs) > 1 else ""
    return refs[0], f"## {refs[0]}: {_plain(task['title'])}{more}"


def render_known_limits(entries: List[dict], state=None, cap: int = KNOWN_LIMITS_MAX) -> str:
    lines = [f"<!-- {HEADER} -->", "# Known limits", "", LIMITS_INTRO]
    active = LG.active_limits(entries)                          # the file is in acceptance order
    shown = active[-cap:] if cap > 0 else []
    grouped: Dict[str, Tuple[str, List[dict]]] = {}
    for entry in reversed(shown):
        key, heading = _limit_group(state, entry["ptask"])
        grouped.setdefault(key, (heading, []))[1].append(entry)
    hidden, gone = len(active) - len(shown), len(LG.retired(entries))
    if hidden:
        lines += ["", f"The newest {len(shown)} open limits are listed; {hidden} older open limit(s) "
                      "are not shown: `repact-task ledger --limits` lists them all."]
    if gone:
        lines += ["", f"{gone} retired limit(s) not shown; `repact-task ledger` counts them."]
    if not grouped:
        lines += ["", "None recorded yet." if not gone else "None open."]
    for heading, limits in grouped.values():
        lines += ["", heading, ""]
        lines += [f"- {_plain(entry['text'])} (`{entry['ptask']}` rev {entry['rev']}, "
                  f"id `{LG.short_id(entry)}`)" for entry in limits]
    return _markdown(lines)


def render_decision_log(entries: List[dict], state=None) -> str:
    lines = [f"<!-- {HEADER} -->", "# Decision log", "", DECISIONS_INTRO, ""]
    decisions = [entry for entry in entries if entry["kind"] == "decision"]
    lines += [f"- **{entry['id']}** `{entry['ptask']}` rev {entry['rev']}: {_plain(entry['text'])}"
              for entry in decisions] or ["None recorded yet."]
    return _markdown(lines)


LEDGER_RENDERERS = {"known_limits": render_known_limits, "decision_log": render_decision_log}


def render_text(name: str, state, ledger: Optional[List[dict]] = None,
                cap: int = KNOWN_LIMITS_MAX) -> str:
    """One view's bytes; the ledger views read `ledger` (ledger.read's entries, [] when None), and
    known_limits lists at most `cap` open limits (limits_cap)."""
    if name == "known_limits":
        return render_known_limits(ledger or [], state, cap)
    if name in LEDGER_RENDERERS:
        return LEDGER_RENDERERS[name](ledger or [], state)
    if name not in RENDERERS:
        raise W.Usage(f"unknown view {name!r} (known: {', '.join([*RENDERERS, *LEDGER_RENDERERS])})")
    return RENDERERS[name](state)


def hand_edited(path: Path) -> Optional[bool]:
    """True when a generated view no longer matches its render hash, False when it does, None
    when the file is absent or carries no render hash (never generated)."""
    try:
        text = Path(path).read_text(encoding="utf-8")
    except OSError:
        return None
    if Path(path).suffix == ".json":
        try:
            doc = json.loads(text)
        except ValueError:
            return True
        if not isinstance(doc, dict) or not isinstance(doc.get(HASH_KEY), str):
            return None
        stored = doc.pop(HASH_KEY)
        return stored != "sha256:" + hashlib.sha256(_json_body(doc).encode("utf-8")).hexdigest()
    body, _, last = text.rstrip("\n").rpartition("\n")
    match = HASH_LINE_RE.match(last)
    if not match:
        return None
    return match.group(1) != hashlib.sha256((body + "\n").encode("utf-8")).hexdigest()


def drifted(tree: Path) -> List[str]:
    """The configured views in `tree` that differ from a render of the log IN `tree`.

    `tree` is a checkout (the main one or a worktree): its own tracked copy of the log is read,
    not the main checkout's, so a committed tree is compared with itself. A matching render hash
    is not enough; the bytes must equal the render. [] when no views are configured."""
    tree = Path(tree)
    views = configured(tree)
    if not views:
        return []
    parsed = PT.read_log(tree / PT.LOG_RELPATH)
    state = PT.replay(parsed.events, parsed.corrupt)
    entries, _ = LG.read(tree)
    cap = limits_cap(tree)
    out = []
    for name, rel in views.items():
        try:
            current = (tree / rel).read_text(encoding="utf-8")
        except OSError:
            current = None
        if current != render_text(name, state, entries, cap):
            out.append(name)
    return out


