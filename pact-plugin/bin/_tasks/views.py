def _write_atomic(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile("w", dir=path.parent, delete=False, suffix=".tmp",
                                     encoding="utf-8") as tmp:
        tmp.write(text)
    os.replace(tmp.name, path)


def render(main: Path, names: Optional[Iterable[str]] = None) -> List[Tuple[str, str, bool]]:
    """Render the configured views (or those named); [(name, path, changed)]."""
    main = Path(main)
    views = configured(main)
    if not views:
        raise W.Usage(f"no views configured in {CONFIG_RELPATH}; run `repact-task render --configure`")
    chosen = list(names or views)
    unknown = [name for name in chosen if name not in views]
    if unknown:
        raise W.Usage(f"not a configured view: {', '.join(unknown)} (configured: {', '.join(views)})")
    state = W.Store(main).state()
    entries, _ = LG.read(main)
    cap = limits_cap(main)
    W._ensure_lines(main / ".gitattributes", merge_lines(views))
    results = []
    for name in chosen:
        path = main / views[name]
        text = render_text(name, state, entries, cap)
        changed = not path.exists() or path.read_text(encoding="utf-8") != text
        if changed:
            _write_atomic(path, text)
        results.append((name, views[name], changed))
    return results


def render_if_configured(main: Path) -> List[Tuple[str, str, bool]]:
    """The re-render after a write: a no-op when no views are configured."""
    return render(main) if configured(main) else []


def _git(main: Path, *args: str) -> subprocess.CompletedProcess:
    return subprocess.run(["git", "-C", str(main), *args], capture_output=True, text=True, timeout=60)


def commit(main: Path) -> str:
    """Render, then commit ONLY the log, its config, the project metadata (.repacted/project.json),
    .gitattributes (the merge lines of the log and the views) and the configured views, with one sentence. Other staged files stay staged and uncommitted
    (`git commit --only -- <paths>`)."""
    main = Path(main)
    views = configured(main)
    if views:
        render(main)
    paths = [p for p in [str(PT.LOG_RELPATH), str(LG.LEDGER_RELPATH), str(CONFIG_RELPATH),
                         str(PROJECT_RELPATH), ".gitattributes", *views.values()]
             if (main / p).exists()]
    added = _git(main, "add", "--", *paths)
    if added.returncode != 0:
        raise W.Refused(f"git add failed: {added.stderr.strip().splitlines()[-1:]}")
    staged = _git(main, "diff", "--cached", "--name-only", "--", *paths)
    changed = staged.stdout.split()
    if not changed:
        return "nothing to commit: the log and its views match HEAD"
    done = _git(main, "commit", "--only", "-q", "-m", COMMIT_MESSAGE, "--", *paths)
    if done.returncode != 0:
        raise W.Refused(f"git commit failed: {(done.stderr or done.stdout).strip()}")
    return f"committed {len(changed)} file(s): {', '.join(changed)}"
