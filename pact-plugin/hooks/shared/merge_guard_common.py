# ─── Patch propagation (lives and dies with the façade) ──────────────────────────
# The suite patches names on this module (monkeypatch.setattr(mgc, "_PER_LEG_OPS", ...),
# `mgc.re = ...`, `mgc.TOKEN_DIR = ...`). Every reader of such a name now lives in a
# package module with its own binding, so a plain setattr here would reach no reader.
# Setting an attribute on this module therefore also sets it on every shell.merge module
# that binds the name (the definer and its importers); the monkeypatch undo takes the same
# route. tests/contract/test_shell_package.py pins it. When the façade retires, the
# patches move to the module that reads the name.
import sys as _sys
import types as _types

_PACKAGE_MODULES = tuple(_sys.modules[f"shell.merge.{_name}"] for _name in ("tokens", "arms", "views", "strip", "inert_legs", "flags", "remotes", "targets", "targets_git", "checkout", "unmintable", "classify", "context"))


class _PropagatingFacade(_types.ModuleType):
    def __setattr__(self, name, value):
        for module in _PACKAGE_MODULES:
            if name in module.__dict__:
                module.__dict__[name] = value
        super().__setattr__(name, value)


_sys.modules[__name__].__class__ = _PropagatingFacade
